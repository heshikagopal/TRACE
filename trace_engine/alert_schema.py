"""
TRACE Alert Schema Module
Defines the standard data structures for security alerts generated by the TRACE detection engine.
Maintains objectivity, preserves supporting evidence IDs, and separates observed facts from hypotheses.
"""

from dataclasses import dataclass, field, asdict
from typing import List, Dict, Any, Optional
from datetime import datetime, timezone


@dataclass
class ThreatAlert:
    """
    Standardised alert representation for TRACE.
    Adheres strictly to evidence citations without asserting legal guilt or unverified conclusions.
    """
    alert_id: str
    rule_id: str
    threat_category: str
    severity: str                           # 'CRITICAL', 'HIGH', 'MEDIUM', 'LOW', 'INFORMATIONAL'
    risk_score: float                       # 0.0 to 100.0
    detection_explanation: str
    triggering_event_ids: List[str]
    evidence_ids: List[str]
    original_timestamps: List[str]
    normalised_timestamps: List[str]
    confidence: str                         # 'Confirmed Fact', 'High Confidence', 'Corroborated Intelligence', 'Unverified Indicator'
    recommended_action: str
    target_entity: str = ""
    source_ip: str = ""
    rule_metadata: Dict[str, Any] = field(default_factory=dict)
    generated_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> Dict[str, Any]:
        """Converts alert object to JSON-serializable dictionary with compatibility aliases."""
        d = asdict(self)
        d["triggered_rule"] = self.rule_id
        d["threat_category"] = self.threat_category
        d["detection_category"] = self.threat_category
        d["explanation"] = self.detection_explanation
        d["related_event_ids"] = self.triggering_event_ids
        d["original_evidence_ids"] = self.evidence_ids
        return d

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "ThreatAlert":
        """Instantiates alert object from dictionary."""
        return cls(**data)
